import fs from 'node:fs';
import path from 'node:path';

export const PRE_COMMIT_HOOK_IDENTIFIER = '# Generated by agentsync security hook';

export const PRE_COMMIT_SCRIPT = `#!/bin/sh
${PRE_COMMIT_HOOK_IDENTIFIER}

echo "🔍 [agentsync] Running pre-commit secret scanning on staged files..."

# Run agentsync scan on staged files
if command -v agentsync >/dev/null 2>&1; then
  agentsync scan --staged
else
  npx --no-install agentsync scan --staged 2>/dev/null || npx agentsync scan --staged
fi

SCAN_EXIT_CODE=$?

if [ $SCAN_EXIT_CODE -ne 0 ]; then
  echo ""
  echo "❌ [agentsync] Commit blocked: Detected sensitive secrets or credentials in staged files!"
  echo "💡 To ignore false positives, update 'security.allowlist_patterns' in agent.yaml."
  echo ""
  exit 1
fi

exit 0
`;

export interface HookInstallResult {
  success: boolean;
  message: string;
  hookPath: string;
}

/**
 * Installs pre-commit hook into .git/hooks/pre-commit
 */
export function installPreCommitHook(projectRoot: string): HookInstallResult {
  const gitDir = path.resolve(projectRoot, '.git');

  if (!fs.existsSync(gitDir)) {
    return {
      success: false,
      message: 'Not a git repository (missing .git directory). Run `git init` first.',
      hookPath: '',
    };
  }

  const hooksDir = path.join(gitDir, 'hooks');
  if (!fs.existsSync(hooksDir)) {
    fs.mkdirSync(hooksDir, { recursive: true });
  }

  const hookPath = path.join(hooksDir, 'pre-commit');

  // Check if hook already exists
  if (fs.existsSync(hookPath)) {
    const existingContent = fs.readFileSync(hookPath, 'utf-8');
    if (existingContent.includes(PRE_COMMIT_HOOK_IDENTIFIER)) {
      // Update content
      fs.writeFileSync(hookPath, PRE_COMMIT_SCRIPT, { mode: 0o755, encoding: 'utf-8' });
      try {
        fs.chmodSync(hookPath, 0o755);
      } catch {
        // Ignore chmod error on Windows
      }
      return {
        success: true,
        message: 'Pre-commit hook updated successfully.',
        hookPath,
      };
    } else {
      // Append or prepend to existing hook
      const mergedContent = `${PRE_COMMIT_SCRIPT}

# Original pre-commit hook below:
${existingContent}`;
      fs.writeFileSync(hookPath, mergedContent, { mode: 0o755, encoding: 'utf-8' });
      try {
        fs.chmodSync(hookPath, 0o755);
      } catch {
        // Ignore chmod error on Windows
      }
      return {
        success: true,
        message: 'agentsync security check prepended to existing pre-commit hook.',
        hookPath,
      };
    }
  }

  fs.writeFileSync(hookPath, PRE_COMMIT_SCRIPT, { mode: 0o755, encoding: 'utf-8' });
  try {
    fs.chmodSync(hookPath, 0o755);
  } catch {
    // Ignore chmod error on Windows
  }

  return {
    success: true,
    message: 'Pre-commit hook installed successfully.',
    hookPath,
  };
}

/**
 * Uninstalls pre-commit hook from .git/hooks/pre-commit
 */
export function uninstallPreCommitHook(projectRoot: string): HookInstallResult {
  const hookPath = path.resolve(projectRoot, '.git', 'hooks', 'pre-commit');

  if (!fs.existsSync(hookPath)) {
    return {
      success: true,
      message: 'No pre-commit hook found to uninstall.',
      hookPath,
    };
  }

  const content = fs.readFileSync(hookPath, 'utf-8');
  if (!content.includes(PRE_COMMIT_HOOK_IDENTIFIER)) {
    return {
      success: false,
      message: 'Pre-commit hook was not installed by agentsync. Leaving untouched.',
      hookPath,
    };
  }

  // If the hook only contains our script, delete the file
  if (content.trim() === PRE_COMMIT_SCRIPT.trim()) {
    fs.unlinkSync(hookPath);
    return {
      success: true,
      message: 'agentsync pre-commit hook removed completely.',
      hookPath,
    };
  }

  // Otherwise remove our portion
  const cleanedContent = content.replace(PRE_COMMIT_SCRIPT, '').trim();
  fs.writeFileSync(hookPath, cleanedContent + '\n', { mode: 0o755, encoding: 'utf-8' });

  return {
    success: true,
    message: 'agentsync check removed from pre-commit hook.',
    hookPath,
  };
}

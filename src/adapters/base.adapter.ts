import type { AgentConfig, TargetAgent } from '../utils/yaml-parser.js';

export interface GeneratedFile {
  filePath: string;
  content: string;
  description: string;
}

export abstract class BaseAdapter {
  protected config: AgentConfig;
  abstract readonly target: TargetAgent;

  constructor(config: AgentConfig) {
    this.config = config;
  }

  /**
   * Generate all target-specific configuration files
   */
  abstract generateFiles(): GeneratedFile[];

  /**
   * Generates a standard auto-generation banner for non-JSON files
   */
  protected getHeaderBanner(style: 'hash' | 'markdown' | 'c-style' = 'hash'): string {
    const bannerText = [
      'AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY',
      'Generated by agentsync (https://github.com/agentsync/agentsync)',
      'Source configuration: agent.yaml',
    ];

    switch (style) {
      case 'markdown':
        return `<!--\n${bannerText.map((l) => `  ${l}`).join('\n')}\n-->\n\n`;
      case 'c-style':
        return `/*\n${bannerText.map((l) => ` * ${l}`).join('\n')}\n */\n\n`;
      case 'hash':
      default:
        return `# ${bannerText.join('\n# ')}\n\n`;
    }
  }
}

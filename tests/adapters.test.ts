import YAML from 'yaml';
import { describe, expect, it } from 'vitest';
import { getAdapter } from '../src/adapters/index.js';
import { AgentConfigSchema, TARGET_AGENTS, type TargetAgent } from '../src/utils/yaml-parser.js';

const sampleConfig = AgentConfigSchema.parse({
  project: {
    name: 'test-project',
    language: 'TypeScript',
    framework: 'Next.js',
  },
  targets: [...TARGET_AGENTS],
  rules: {
    system_prompt: 'Follow strict engineering standards.',
    coding_style: ['Use strict TypeScript', 'Prefer pure functions'],
    forbidden_patterns: ['No hardcoded secrets'],
    architecture_notes: 'Keep domain logic separate from UI.',
  },
  skills: [
    {
      name: 'review',
      description: 'Review code changes',
      instructions: 'Check edge cases and types.',
    },
  ],
  mcp_servers: {
    filesystem: {
      command: 'npx',
      args: ['-y', '@modelcontextprotocol/server-filesystem', '.'],
      env: { NODE_ENV: 'development' },
    },
  },
});

describe('adapters', () => {
  const expectedPaths: Record<TargetAgent, string[]> = {
    cursor: ['.cursorrules', '.cursor/mcp.json'],
    claude: ['CLAUDE.md', '.mcp.json'],
    cline: ['.clinerules'],
    opencode: ['.opencode/instructions.md', 'opencode.json'],
    aider: ['CONVENTIONS.md', '.aider.conf.yml'],
  };

  it.each(TARGET_AGENTS)('generates valid files and banners for %s', (target) => {
    const adapter = getAdapter(target, sampleConfig);
    const files = adapter.generateFiles();
    const paths = files.map((f) => f.filePath);

    expect(paths).toEqual(expectedPaths[target]);

    for (const file of files) {
      expect(file.content.length).toBeGreaterThan(0);

      if (file.filePath.endsWith('.json')) {
        const parsed = JSON.parse(file.content);
        expect(parsed).toBeTypeOf('object');
      } else if (file.filePath.endsWith('.yml') || file.filePath.endsWith('.yaml')) {
        expect(file.content).toContain('Generated by agentsync');
        const parsed = YAML.parse(file.content);
        expect(parsed).toBeTypeOf('object');
      } else {
        expect(file.content).toContain('Generated by agentsync');
        expect(file.content).toContain('test-project');
      }
    }
  });
});
